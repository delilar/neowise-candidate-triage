import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { classify } from "./mock-ai.mjs";
import { pathToFileURL } from "node:url";

const html = await readFile(new URL("./index.html", import.meta.url));

function json(response, status, body) {
  response.writeHead(status, { "Content-Type": "application/json; charset=utf-8" });
  response.end(JSON.stringify(body));
}

async function handleTriage(request, response) {
  const chunks = [];
  for await (const chunk of request) chunks.push(chunk);
  let input;
  try {
    input = JSON.parse(Buffer.concat(chunks).toString("utf8"));
  } catch {
    return json(response, 400, { status: "invalid_input" });
  }
  if (typeof input?.text !== "string" || !input.text.trim()) {
    return json(response, 400, { status: "invalid_input" });
  }
  return json(response, 200, await triage(input.text));
}

// Keep provider failures and untrusted model output behind one boundary.
export async function triage(text, provider = classify) {
  const controller = new AbortController();
  let timer;
  try {
    const timeout = new Promise((_, reject) => {
      timer = setTimeout(() => {
        controller.abort();
        reject(new Error("Model timeout"));
      }, 300);
    });
    // The race also bounds providers that ignore AbortSignal.
    const raw = await Promise.race([provider(text, { signal: controller.signal }), timeout]);
    const result = JSON.parse(raw);
    if (!result || typeof result !== "object" || Array.isArray(result)
      || !["delivery", "pricing", "other"].includes(result.topic)
      || typeof result.draft !== "string" || !result.draft.trim()) {
      throw new Error("Invalid model output");
    }
    return { status: "ready", topic: result.topic, draft: result.draft.trim() };
  } catch {
    return { status: "manual_review", topic: null, draft: null };
  } finally {
    clearTimeout(timer);
  }
}

export function createApp() {
  return createServer(async (request, response) => {
    if (request.method === "GET" && request.url === "/") {
      response.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
      response.end(html);
      return;
    }
    if (request.method !== "POST" || request.url !== "/api/triage") {
      return json(response, 404, { status: "not_found" });
    }
    try {
      await handleTriage(request, response);
    } catch {
      json(response, 500, { status: "server_error" });
    }
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  createApp().listen(Number(process.env.PORT || 3000), "127.0.0.1");
}
